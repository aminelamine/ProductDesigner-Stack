#!/usr/bin/env node

/**
 * PDS Stack V3 — Interactive Installer
 * npx pds-stack install
 *
 * Generates STACK.md, CLAUDE.md, agent system prompts,
 * and PROJECT_BRIEF_TEMPLATE from answers to interactive prompts.
 */

const prompts = require('prompts');
const kleur = require('kleur');
const fs = require('fs');
const path = require('path');

// ─── UI Helpers ───────────────────────────────────────────────────────────────

