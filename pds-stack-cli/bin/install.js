// ─── File Generators ──────────────────────────────────────────────────────────

function generateSTACK(answers) {
  const modules = answers.modules || ['core'];
  return `# STACK.md — PDS Stack configuration
# Generated by: npx pds-stack install
# Edit to match your project constraints.
# All agents (RAY, BOB, ANALYZER) read this file before every session.

framework: ${answers.framework}
language: ${answers.language}
ui_lib: ${answers.ui_lib}
strict_mode: ${answers.language === 'typescript' ? 'true' : 'false'}
line_cap: 150
motion_default: L0
quality_brief_type: ${answers.quality_brief_type}

# Modules installed
modules:
  core: true
  discovery: ${modules.includes('discovery') ? 'true' : 'false'}
  delivery: ${modules.includes('delivery') ? 'true' : 'false'}
  design: ${modules.includes('design') ? 'true' : 'false'}
  epic: ${modules.includes('epic') ? 'true' : 'false'}

# Agent language
language_agents: ${answers.language_agents}
`;
}

function generateCLAUDE(answers) {
  const modules = answers.modules || ['core'];
  const hasDiscovery = modules.includes('discovery');
  const hasDelivery = modules.includes('delivery');

  const stackLine = {
    nextjs: 'Next.js · TypeScript strict · Tailwind · Shadcn/ui · Lucide React',
    nuxt: 'Nuxt · TypeScript strict · Tailwind · Shadcn Vue',
    sveltekit: 'SvelteKit · TypeScript strict · Tailwind',
    astro: 'Astro · TypeScript strict · Tailwind',
    remix: 'Remix · TypeScript strict · Tailwind · Shadcn/ui',
    other: `${answers.framework} · ${answers.language} · ${answers.ui_lib}`,
  }[answers.framework] || `${answers.framework} · ${answers.language}`;

  const strictConstraints = answers.language === 'typescript'
    ? '→  TypeScript strict — zero `any`, zero `@ts-ignore`\n'
    : '';

  const shadcnConstraints = answers.ui_lib === 'shadcn'
    ? '→  `/components/ui/` is read-only. Shadcn owns it.\n→  No UI lib outside `agent-system/context/design_guide.md` without Talent sign-off\n'
    : '';

  return `# ⬡ PDS STACK V3 — ${answers.project_name}

Stack   →  ${stackLine}
Agents  →  RAY · BOB · ANALYZER${hasDiscovery ? ' · EVE' : ''}${hasDelivery ? ' · SHIP' : ''}

> Stack constraints defined in STACK.md — agents read it before every session.

---

## HARD CONSTRAINTS

→  No code without \`statut: VALIDATED\` in spec
→  No code without Quality Brief approval — BOB gate is non-negotiable
→  Scope frozen at VALIDATED — additions require new RAY cycle
${shadcnConstraints}${strictConstraints}→  Components cap at 150 lines — split if exceeded
→  Consult \`agent-system/adr/ADR_INDEX.md\` before any architecture or dependency decision

---

## AGENTS

/ray       →  RAY      challenges idea · writes spec (T1/T2/T3) · creates ADRs
                       reads: STACK.md · client_vision · roadmap · ADR_INDEX · last 3 learnings
                       spec: numbered tasks · \`## OUT OF SCOPE\` block · \`statut: VALIDATED\`
                       scope frozen at VALIDATED — additions require new RAY cycle

/bob       →  BOB      Quality Brief (gate) · implements · commits
                       reads: spec · STACK.md · design_guide · ADR_INDEX
                       one feature per session — reset context before starting next
                       commit after each task — \`feat(N): task-title\`
                       no code before Quality Brief explicit approval

/analyzer  →  ANALYZER scores /20 · verdict · writes learnings
                       18–20: SHIPPED · 14–17: SHIPPED WITH NOTES · 10–13: REWORK → BOB · <10: RE-SPEC → RAY
${hasDiscovery ? `
/eve       →  EVE      discovery · problem validation · pre-fills PROJECT_BRIEF §1–§2
                       use when: problem unclear before briefing · optional · not a gate
` : ''}${hasDelivery ? `
/ship      →  SHIP     delivery · release notes · KPI reminders
                       requires: ANALYZER verdict ≥ 14 · optional module
` : ''}
/design-workflow → Bridge DS · generates Figma frame from RAY spec *(optional)*
`;
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  print.header();

  const answers = await prompts(questions, {
    onCancel: () => {
      print.nl();
      print.warn('Installation cancelled.');
      process.exit(0);
    },
  });

  if (!answers.framework) {
    print.error('No answers provided. Exiting.');
    process.exit(1);
  }

  print.nl();
  print.divider();
  print.nl();

  const cwd = process.cwd();
  const templateDir = path.join(__dirname, '..', 'templates');
  const modules = answers.modules || ['core'];

  // 1. Generate STACK.md
  print.step('Generating STACK.md...');
  fs.writeFileSync(path.join(cwd, 'STACK.md'), generateSTACK(answers), 'utf8');
  print.done('STACK.md created');

  // 2. Generate CLAUDE.md
  print.step('Generating CLAUDE.md...');
  fs.writeFileSync(path.join(cwd, 'CLAUDE.md'), generateCLAUDE(answers), 'utf8');
  print.done('CLAUDE.md created');

  // 3. Copy agent system from templates
  print.step('Generating agent system...');
  const agentSystemSrc = path.join(templateDir, 'core', 'agent-system');
  const agentSystemDest = path.join(cwd, 'agent-system');

  if (fs.existsSync(agentSystemSrc)) {
    copyDir(agentSystemSrc, agentSystemDest);
    print.done('agent-system/ created');
  } else {
    print.warn('Templates not found — run from the pds-stack package directory');
  }

  // 4. Copy optional modules
  for (const mod of ['discovery', 'delivery', 'design', 'epic']) {
    if (modules.includes(mod)) {
      print.step(`Installing module: ${mod}...`);
      const modSrc = path.join(templateDir, 'modules', mod);
      if (fs.existsSync(modSrc)) {
        copyDir(modSrc, path.join(cwd, 'agent-system'));
        print.done(`Module ${mod} installed`);
      }
    }
  }

  // 5. Generate PROJECT_BRIEF at correct tier
  print.step(`Generating PROJECT_BRIEF (${answers.brief_depth})...`);
  const briefSrc = path.join(templateDir, 'core', `PROJECT_BRIEF_${answers.brief_depth}.md`);
  const briefDest = path.join(cwd, 'agent-system', 'PROJECT_BRIEF_TEMPLATE.md');
  if (fs.existsSync(briefSrc)) {
    fs.copyFileSync(briefSrc, briefDest);
    print.done('PROJECT_BRIEF_TEMPLATE.md created');
  }

  // 6. Done
  print.nl();
  print.divider();
  print.nl();
  console.log(kleur.bold().green('  ✓ PDS Stack V3 installed.'));
  print.nl();
  console.log(kleur.dim('  Next steps:'));
  console.log(kleur.dim('  1. Fill') + ' agent-system/PROJECT_BRIEF_TEMPLATE.md');
  console.log(kleur.dim('  2. Run') + ' /ray');
  console.log(kleur.dim('  3. BOB will ask for a Quality Brief before writing any code.'));
  print.nl();
  console.log(kleur.dim('  Docs: https://github.com/aminelamine/ProductDesigner-Stack'));
  print.nl();
}

// ─── Utils ────────────────────────────────────────────────────────────────────

function copyDir(src, dest) {
  if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

main().catch((err) => {
  console.error(kleur.red('\n  Fatal error:'), err.message);
  process.exit(1);
});
