#!/usr/bin/env node

/**
 * PDS Stack — Distribution parity check
 *
 * The stack is a web of thin loaders: a command says "load agent-system/X.md", a skill says
 * "the full protocol lives in Y.md". If a referenced file is not packaged in templates/, the
 * install ships a broken system and nothing tells you — that is exactly how v3.0.3 went out
 * without its Quality Brief gate.
 *
 * This script simulates a maximal install (core + every module + every tool surface), collects
 * every file path referenced by the shipped files, and fails if one of them is not shipped.
 *
 *   node bin/check-parity.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT      = path.join(__dirname, '..');
const TEMPLATES = path.join(ROOT, 'templates');
const MODULES   = ['discovery', 'delivery', 'design', 'epic'];
const TOOLS     = ['claude', 'cursor', 'gemini', 'copilot', 'codex'];

// Generated by the installer, never packaged as a template file.
const GENERATED = new Set(['STACK.md', 'CLAUDE.md', 'GEMINI.md', '.cursor/rules/pds-stack.mdc']);

// Written by the user or by the agents at runtime — a reference to them is not a packaging bug.
const RUNTIME_DIRS = [
  'agent-system/specs/active/', 'agent-system/specs/shipped/', 'agent-system/specs/dropped/',
  'agent-system/specs/epics/', 'agent-system/sessions/', 'agent-system/learnings/',
  'agent-system/adr/examples/', 'design-system/',
];

const c = {
  dim:  (s) => `\x1b[2m${s}\x1b[0m`,
  red:  (s) => `\x1b[31m${s}\x1b[0m`,
  green:(s) => `\x1b[32m${s}\x1b[0m`,
  yellow:(s) => `\x1b[33m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
};

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/**
 * Map every template file to the path it lands on after `npx pds-stack install`,
 * mirroring the copy rules in install.js.
 */
function simulateInstall() {
  const landed = new Map(); // installed path → template source

  const add = (installed, src) => landed.set(installed.split(path.sep).join('/'), src);

  // core/agent-system/** → agent-system/**
  for (const f of walk(path.join(TEMPLATES, 'core', 'agent-system'))) {
    add(path.join('agent-system', path.relative(path.join(TEMPLATES, 'core', 'agent-system'), f)), f);
  }
  // core/tools/<tool>/** → ./**
  for (const tool of TOOLS) {
    const base = path.join(TEMPLATES, 'core', 'tools', tool);
    for (const f of walk(base)) add(path.relative(base, f), f);
  }
  // modules/<mod>/** (minus tools/) → agent-system/**
  for (const mod of MODULES) {
    const base = path.join(TEMPLATES, 'modules', mod);
    for (const f of walk(base)) {
      const rel = path.relative(base, f);
      if (rel.split(path.sep)[0] === 'tools') continue;
      add(path.join('agent-system', rel), f);
    }
    // modules/<mod>/tools/<tool>/** → ./**
    for (const tool of TOOLS) {
      const tbase = path.join(base, 'tools', tool);
      for (const f of walk(tbase)) add(path.relative(tbase, f), f);
    }
  }
  // core/PROJECT_BRIEF_T?.md → agent-system/PROJECT_BRIEF_TEMPLATE.md
  if (fs.existsSync(path.join(TEMPLATES, 'core', 'PROJECT_BRIEF_T2.md'))) {
    add(path.join('agent-system', 'PROJECT_BRIEF_TEMPLATE.md'), 'core/PROJECT_BRIEF_T{1,2,3}.md');
  }
  return landed;
}

const REF_RE = /(?:^|[\s`("'\[])((?:agent-system|\.claude|\.cursor|\.gemini|\.github|\.agents)\/[A-Za-z0-9_./-]+\.(?:md|mdc|toml))/g;

function isIgnorable(ref) {
  if (GENERATED.has(ref)) return true;
  if (ref.includes('[') || ref.includes('*') || ref.includes('{')) return true;
  if (/feature_\d|feature_ID|_\[ID\]/.test(ref)) return true;
  return RUNTIME_DIRS.some((d) => ref.startsWith(d));
}

/**
 * Second failure mode: the template exists but its content has drifted from the repo.
 * Editing agent-system/agents/BOB_system_prompt.md and forgetting the template copy ships an
 * installer one revision behind the source — the same class of bug, one step subtler.
 *
 * Only files that must be byte-identical are compared. Context stubs, ADRs and specs are
 * deliberately different: the repo's are this project's, the templates' are blank starting points.
 */
const MIRRORED = [
  ['templates/core/agent-system/agents',        '../agent-system/agents'],
  ['templates/core/agent-system/orchestration', '../agent-system/orchestration'],
  ['templates/core/agent-system/resources',     '../agent-system/resources'],
  ['templates/core/tools/claude/.claude/commands', '../.claude/commands'],
  ['templates/core/tools/cursor/.cursor',       '../.cursor'],
  ['templates/core/tools/gemini/.gemini',       '../.gemini'],
  ['templates/core/tools/copilot/.github/prompts', '../.github/prompts'],
  ['templates/core/tools/codex/.agents',        '../.agents'],
];

function checkDrift() {
  const drifted = [];
  for (const [tplRel, repoRel] of MIRRORED) {
    const tplDir  = path.join(ROOT, tplRel);
    const repoDir = path.join(ROOT, repoRel);
    if (!fs.existsSync(tplDir) || !fs.existsSync(repoDir)) continue;
    for (const f of walk(tplDir)) {
      const rel  = path.relative(tplDir, f);
      const twin = path.join(repoDir, rel);
      if (!fs.existsSync(twin)) continue; // module-gated files, checked by the reference pass
      if (fs.readFileSync(f, 'utf8') !== fs.readFileSync(twin, 'utf8')) {
        drifted.push({
          template: path.join(tplRel, rel).split(path.sep).join('/'),
          source:   path.join(repoRel, rel).replace(/^\.\.\//, '').split(path.sep).join('/'),
        });
      }
    }
  }
  return drifted;
}

/**
 * Third failure mode, and the one no test can catch for you: a gate was reweakened.
 *
 * The gates are reasoning-based — a prompt edit that hollows one out compiles fine and breaks no
 * test. The only detector is re-running the pulse (see _stack-test-pulse/README.md). This pass
 * cannot run it, so it does the next useful thing: tells you the recorded run no longer describes
 * the files it validated. It warns, never fails — a stale benchmark is a fact to know at publish
 * time, not a reason to block a release.
 */
const PULSE_DIR = path.join(ROOT, '..', '_stack-test-pulse');

// Files whose content defines what a gate actually does.
function gateFiles() {
  const dirs = [
    path.join(ROOT, '..', 'agent-system', 'agents'),
    path.join(ROOT, '..', 'agent-system', 'orchestration'),
    path.join(ROOT, 'templates', 'core', 'hooks'),
  ];
  const out = [];
  for (const d of dirs) {
    for (const f of walk(d)) out.push(f);
  }
  return out.sort();
}

function hashOf(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 16);
}

function currentBaseline() {
  const files = {};
  for (const f of gateFiles()) {
    files[path.relative(path.join(ROOT, '..'), f).split(path.sep).join('/')] = hashOf(f);
  }
  return files;
}

function checkPulse() {
  const bfile = path.join(PULSE_DIR, 'baseline.json');
  if (!fs.existsSync(bfile)) return null;
  let recorded;
  try { recorded = JSON.parse(fs.readFileSync(bfile, 'utf8')); } catch { return null; }
  const now = currentBaseline();
  const changed = [];
  for (const [f, h] of Object.entries(now)) {
    if (recorded.files[f] !== h) changed.push(recorded.files[f] ? f : `${f} (new)`);
  }
  for (const f of Object.keys(recorded.files)) {
    if (!(f in now)) changed.push(`${f} (removed)`);
  }
  return { date: recorded.last_run, score: recorded.score, changed };
}

function acceptPulse() {
  const bfile = path.join(PULSE_DIR, 'baseline.json');
  if (!fs.existsSync(PULSE_DIR)) {
    console.log(c.red('  ✗ no _stack-test-pulse/ directory — nothing to accept.'));
    process.exit(1);
  }
  const prev = fs.existsSync(bfile) ? JSON.parse(fs.readFileSync(bfile, 'utf8')) : {};
  const next = {
    last_run: new Date().toISOString().slice(0, 10),
    score: prev.score || null,
    note: 'Hashes of the gate-defining files as of the last pulse run. See README.md.',
    files: currentBaseline(),
  };
  fs.writeFileSync(bfile, JSON.stringify(next, null, 2) + '\n');
  console.log('');
  console.log(c.green(`  ✓ pulse baseline refreshed — ${Object.keys(next.files).length} gate files, dated ${next.last_run}`));
  console.log(c.dim('    Update `score` by hand from SCORING.md.'));
  console.log('');
}

/**
 * Fourth failure mode, found by pulse run 3: a rule that looks for something the shipped files
 * do not contain. flow.md hunted for `[À COMPLÉTER]` markers; the English templates had none, so
 * the conductor declared two empty context files complete and walked past its own gate.
 *
 * Existence checks cannot catch this — both files existed and both were packaged. What was
 * missing was that the detector and its target agreed.
 */
function checkDetectors() {
  const problems = [];
  const flow = path.join(TEMPLATES, 'core', 'agent-system', 'orchestration', 'flow.md');
  const ctxDir = path.join(TEMPLATES, 'core', 'agent-system', 'context');
  if (!fs.existsSync(flow) || !fs.existsSync(ctxDir)) return problems;

  const flowText = fs.readFileSync(flow, 'utf8');
  // Only STEP 1 — elsewhere in the flow, `[RAY]` and friends are agent prefixes, not
  // placeholders, and counting them would let a template pass without a real marker.
  // Anchor on the section headings, not the overview diagram that also names both steps.
  const from = flowText.indexOf('## STEP 1');
  const to   = flowText.indexOf('## STEP 2', from < 0 ? 0 : from);
  const step1 = flowText.slice(from < 0 ? 0 : from, to < 0 ? flowText.length : to);
  const AGENT_PREFIXES = new Set(['[RAY]', '[BOB]', '[ANALYZER]', '[EVE]', '[SHIP]', '[Talent]']);
  const markers = [...new Set([...step1.matchAll(/`(\[[^`\]]{2,20}\])`/g)].map((m) => m[1]))]
    .filter((m) => !AGENT_PREFIXES.has(m));
  if (markers.length === 0) {
    problems.push('flow.md names no placeholder marker — STEP 1 cannot detect anything');
    return problems;
  }

  for (const f of fs.readdirSync(ctxDir)) {
    if (!f.endsWith('.md')) continue;
    const text = fs.readFileSync(path.join(ctxDir, f), 'utf8');
    if (!markers.some((m) => text.includes(m))) {
      problems.push(`context/${f} contains none of the markers flow.md looks for (${markers.join(', ')})`);
    }
  }
  return problems;
}

/**
 * Fifth failure mode, found by pulse run 5: a rule that cites a section which does not exist.
 * flow.md sent the conductor to a "propagation table" at the end of PROJECT_BRIEF_TEMPLATE.md and
 * forbade inventing a structure. The file shipped; the section never did. Both the reference pass
 * and the marker pass went green, because the file was there.
 *
 * Catches references of the shape:  `some/path.md` ("Section title")
 */
function checkSectionAnchors() {
  const problems = [];
  const RE = /`(agent-system\/[A-Za-z0-9_./-]+\.md)`\s*\(\s*"([^"]{4,80})"\s*\)/g;
  const landed = simulateInstall();

  for (const [installedPath, src] of landed) {
    if (!/\.md$/.test(src) || !fs.existsSync(src)) continue;
    const text = fs.readFileSync(src, 'utf8');
    let m;
    RE.lastIndex = 0;
    while ((m = RE.exec(text)) !== null) {
      const [, target, section] = m;
      const targetSrc = landed.get(target);
      if (!targetSrc) continue; // the reference pass already reports a missing file
      // PROJECT_BRIEF_TEMPLATE is installed from one of three tiered sources — check all of them.
      const candidates = targetSrc.includes('{1,2,3}')
        ? ['T1', 'T2', 'T3'].map((t) => path.join(TEMPLATES, 'core', `PROJECT_BRIEF_${t}.md`))
        : [targetSrc];
      for (const c of candidates) {
        if (!fs.existsSync(c)) continue;
        if (!fs.readFileSync(c, 'utf8').includes(section)) {
          problems.push(`${installedPath} cites "${section}" in ${target}, absent from ${path.relative(ROOT, c)}`);
        }
      }
    }
  }
  return problems;
}

function main() {
  if (process.argv.includes('--accept-pulse')) return acceptPulse();

  const landed = simulateInstall();
  const missing = [];
  let scanned = 0;

  for (const [installedPath, src] of landed) {
    if (!/\.(md|mdc|toml)$/.test(src)) continue;
    if (!fs.existsSync(src)) continue;
    scanned++;
    const text = fs.readFileSync(src, 'utf8');
    const seen = new Set();
    let m;
    REF_RE.lastIndex = 0;
    while ((m = REF_RE.exec(text)) !== null) {
      const ref = m[1];
      if (seen.has(ref) || isIgnorable(ref) || landed.has(ref)) continue;
      seen.add(ref);
      missing.push({ from: installedPath, ref });
    }
  }

  console.log('');
  console.log(c.bold('  ⬡ PDS Stack — distribution parity'));
  console.log(c.dim(`  ${landed.size} files land on a full install · ${scanned} scanned for references`));
  console.log('');

  const drifted   = checkDrift();
  const detectors = checkDetectors();
  const anchors   = checkSectionAnchors();
  const pulse     = checkPulse();

  const reportPulse = () => {
    if (!pulse) return;
    if (pulse.changed.length === 0) {
      console.log(c.green(`  ✓ pulse benchmark current (${pulse.date}${pulse.score ? `, ${pulse.score}` : ''}).`));
      return;
    }
    console.log(c.yellow(`  ⚠ ${pulse.changed.length} gate file(s) changed since the last pulse run (${pulse.date}) — benchmark is stale`));
    for (const f of pulse.changed) console.log(c.dim(`      ${f}`));
    console.log(c.dim('      Re-run it (_stack-test-pulse/README.md), then: check-parity.js --accept-pulse'));
  };

  if (missing.length === 0 && drifted.length === 0 && detectors.length === 0 && anchors.length === 0) {
    console.log(c.green('  ✓ every referenced file is packaged.'));
    console.log(c.green('  ✓ no drift between the repo and the templates.'));
    console.log(c.green('  ✓ detection rules match the files they target.'));
    console.log(c.green('  ✓ cited sections exist in the files that carry them.'));
    reportPulse();
    console.log('');
    return;
  }

  if (anchors.length) {
    console.log(c.red(`  ✗ ${anchors.length} cited section(s) do not exist:`));
    console.log('');
    for (const a of anchors) console.log(`    ${c.red(a)}`);
    console.log('');
  }

  if (detectors.length) {
    console.log(c.red(`  ✗ ${detectors.length} detection rule(s) do not match their target:`));
    console.log('');
    for (const d of detectors) console.log(`    ${c.red(d)}`);
    console.log('');
  }

  if (drifted.length) {
    console.log(c.red(`  ✗ ${drifted.length} template(s) have drifted from their source:`));
    console.log('');
    for (const { template, source } of drifted) {
      console.log(`    ${c.red(template)}`);
      console.log(c.dim(`      differs from ${source}`));
    }
    console.log('');
    console.log(c.dim('  Fix: cp the source over the template, or reconcile them deliberately.'));
    console.log('');
  }

  if (missing.length === 0) { process.exit(1); }

  console.log(c.red(`  ✗ ${missing.length} reference(s) point at files the install never creates:`));
  console.log('');
  for (const { from, ref } of missing) {
    console.log(`    ${c.red(ref)}`);
    console.log(c.dim(`      referenced by ${from}`));
  }
  console.log('');
  console.log(c.dim('  Fix: add the file under pds-stack-cli/templates/, or drop the reference.'));
  console.log('');
  process.exit(1);
}

main();
